import os, json, tempfile

def save_state(state):
    # Get the directory of the target file
    target_dir = os.path.dirname(STATE_FILE)

    # 1. Create temp file in the SAME directory to ensure atomic replace
    fd, tmp = tempfile.mkstemp(dir=target_dir)

    try:
        # 2. Write data using the file descriptor
        with os.fdopen(fd, "w") as f:
            json.dump(state, f, default=str)
            # Optional: ensure data is flushed to physical disk
            f.flush()
            os.fsync(f.fileno())

        # 3. Atomically replace the target file
        os.replace(tmp, STATE_FILE)
    except Exception:
        # 4. Clean up the temp file if something goes wrong
        if os.path.exists(tmp):
            os.remove(tmp)
        raise



