def create_session(total_retries=5, backoff_factor=0.5, status_forcelist=(429, 500, 502, 503, 504)):
    session = requests.Session()
    retry = Retry(
        total=total_retries,
        read=total_retries,
        connect=total_retries,
        backoff_factor=backoff_factor,
        status_forcelist=status_forcelist,
        allowed_methods=frozenset(['GET','POST','PUT','DELETE','HEAD','OPTIONS'])
    )
    adapter = HTTPAdapter(max_retries=retry)
    session.mount("http://", adapter)
    session.mount("https://", adapter)
    return session

# create a global session once
HTTP_SESSION = create_session()

def safe_get(url, params=None, timeout=10):
    try:
        r = HTTP_SESSION.get(url, params=params, timeout=timeout)
        r.raise_for_status()
        return r
    except requests.exceptions.RequestException as e:
        # raise up for caller to handle, but include message
        raise RuntimeError(f"HTTP GET failed: {e}") from e

